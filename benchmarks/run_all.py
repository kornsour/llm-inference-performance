"""Run the full benchmark suite and write JSON + a markdown results page.

    python benchmarks/run_all.py                 # CPU
    python benchmarks/run_all.py --device cuda    # GPU (same harness)

Writes benchmarks/results/latest.json and docs/results.md, and appends the
run to benchmarks/results/history.duckdb (see llminf.history and
`make bench-history`) so this run is compared against past ones instead of
overwriting them.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from llminf import history  # noqa: E402
from llminf.bench import BenchConfig, run_suite  # noqa: E402
from llminf.model import GPTConfig  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def render_markdown(r: dict) -> str:
    env, m, c = r["env"], r["model"], r["config"]
    kv = r["kv_cache"]
    lines: list[str] = []
    lines.append("# Benchmark results\n")
    lines.append(
        f"> Generated by `benchmarks/run_all.py` on **{env['device_name']}** "
        f"({env['device']}), torch {env['torch']}, Python {env['python']}, "
        f"{env['threads']} threads.\n")
    lines.append(
        f"> CPU: {env['cpu_model']} · platform: {env['platform']} · "
        f"generated {env['timestamp_utc']} · git {env['git_sha']} · "
        f"`{' '.join(env['argv'])}`\n")
    lines.append(
        f"**Model:** {m['params_m']}M params · {m['n_layer']}L/{m['n_head']}H/"
        f"{m['n_embd']}d · block {m['block_size']} · vocab {m['vocab_size']}. "
        f"**Workload:** prompt {c['prompt_len']} → {c['new_tokens']} new tokens, "
        f"{c['repeats']} repeats.\n")

    lines.append("\n## 1. KV-cache (greedy decode, identical outputs)\n")
    lines.append(
        f"| variant | tokens/sec | p50 latency (ms, n={c['repeats']}) | "
        f"p95 latency (ms, n={c['repeats']}) | TTFT p50 (ms, n={c['repeats']}) | "
        f"peak mem (MB) |")
    lines.append("| --- | --- | --- | --- | --- | --- |")
    for key, label in (("cache_off", "no cache (O(T²))"), ("cache_on", "KV-cache (O(T))")):
        d = kv[key]
        lines.append(
            f"| {label} | {d['tokens_per_s_mean']} | {d['latency']['p50_ms']} | "
            f"{d['latency']['p95_ms']} | {d['ttft_ms_p50']} | {d['peak_mem_mb']} |")
    lines.append(f"\n**KV-cache speedup: {kv['speedup_x']}× tokens/sec.**\n")
    lines.append(
        f"The cache is memory *spent*, not saved: it holds "
        f"**{kv['resident_kv_cache_mb']} MB** of K/V resident at the end of this run "
        f"({c['prompt_len']} + {c['new_tokens']} tokens), and grows linearly with "
        f"sequence length and batch size. Peak memory is the high-water mark of "
        f"tensor bytes allocated inside each decode, above the resident model — see "
        f"[`docs/methodology.md`](methodology.md).\n")

    lines.append("\n## 2. Batching throughput (KV-cache on)\n")
    lines.append("| batch size | tokens/sec | speedup vs b=1 | elapsed (s) |")
    lines.append("| --- | --- | --- | --- |")
    for row in r["batching"]["rows"]:
        lines.append(
            f"| {row['batch_size']} | {row['tokens_per_s']} | "
            f"{row['speedup_vs_b1']}× | {row['elapsed_s']} |")

    q = r["quantization"]
    lines.append("\n## 3. int8 dynamic quantization\n")
    lines.append("| metric | fp32 | int8 | delta |")
    lines.append("| --- | --- | --- | --- |")
    lines.append(f"| model size (MB) | {q['fp32_size_mb']} | {q['int8_size_mb']} | "
                 f"{q['size_reduction_x']}× smaller |")
    lines.append(
        f"| latency (ms), median of {q['latency_repeats']} | "
        f"{q['fp32_latency_ms_median']} | {q['int8_latency_ms_median']} | — |")
    lines.append(f"\nNumerical drift (logit MSE fp32→int8): **{q['logit_mse']}**.\n")
    lines.append(
        f"> This section's latency is a **median of {q['latency_repeats']} samples** —"
        f" a different statistic, from a different sample count, than the p50/p95"
        f" columns in sections 1-2 above (an interpolated percentile of "
        f"{c['repeats']} samples). Not directly comparable to those columns.\n")
    if q["latency_device"] != env["device"]:
        lines.append(
            f"\n> torch.ao dynamic quantization is a CPU-only path, so this section "
            f"is measured on **{q['latency_device']}** even though the rest of this "
            f"run used **{env['device']}**.\n")

    rn = r["rmsnorm"]
    lines.append("\n## 4. Fused RMSNorm kernel (on the decode path)\n")
    lines.append(f"Backend: **{rn['backend']}**.\n")
    lines.append("| rows × cols | unfused (ms) | fused (ms) | unfused GB/s | fused GB/s | speedup |")
    lines.append("| --- | --- | --- | --- | --- | --- |")
    for row in rn["rows"]:
        lines.append(
            f"| {row['rows']}×{row['cols']} | {row['unfused_latency_ms_p50']} | "
            f"{row['fused_latency_ms_p50']} | {row['unfused_gbps']} | {row['fused_gbps']} | "
            f"{row['speedup_x']}× |")
    if rn["backend"] != "cuda-fused":
        lines.append(
            "\n> No CUDA device was available for this run, so both columns exercise the "
            "same PyTorch reference path — `rmsnorm.load_error()` carries the compiler "
            "output if a CUDA build was attempted and failed. See "
            "[`kernels/README.md`](../kernels/README.md) for the fused kernel and "
            "[`docs/methodology.md`](methodology.md) for how it's built.\n")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--device", default="cpu")
    ap.add_argument("--quick", action="store_true", help="tiny model / fewer tokens")
    args = ap.parse_args(argv)

    cfg = GPTConfig.tiny() if args.quick else GPTConfig.small()
    bcfg = BenchConfig(new_tokens=32, repeats=2, batch_sizes=(1, 2, 4)) if args.quick \
        else BenchConfig()

    report = run_suite(device=args.device, cfg=cfg, bcfg=bcfg)
    md = render_markdown(report)
    results_dir = ROOT / "benchmarks" / "results"
    results_dir.mkdir(parents=True, exist_ok=True)
    print(md)

    if args.quick:
        # Smoke run on a tiny model — never overwrite the committed full-run
        # artifacts (docs/results.md, latest.json); write a throwaway instead.
        out = results_dir / "quick.json"
        out.write_text(json.dumps(report, indent=2))
        print(f"[--quick] wrote {out.relative_to(ROOT)} — canonical docs/results.md "
              "and latest.json left untouched.")
        return 0

    (results_dir / "latest.json").write_text(json.dumps(report, indent=2))
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "results.md").write_text(md)
    history.append_run(report)
    print("wrote benchmarks/results/latest.json, docs/results.md, "
          "and appended a row to benchmarks/results/history.duckdb "
          "(see `make bench-history`)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
