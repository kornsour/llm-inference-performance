"""Run the full benchmark suite and write JSON + a markdown results page.

    python benchmarks/run_all.py                 # CPU
    python benchmarks/run_all.py --device cuda    # GPU (same harness)

Writes benchmarks/results/latest.json and docs/results.md.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from llminf.bench import BenchConfig, run_suite  # noqa: E402
from llminf.model import GPTConfig  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def render_markdown(r: dict) -> str:
    env, m, c = r["env"], r["model"], r["config"]
    kv = r["kv_cache"]
    lines: list[str] = []
    lines.append("# Benchmark results\n")
    lines.append(
        f"> Generated by `benchmarks/run_all.py` on **{env['device_name']}** "
        f"({env['device']}), torch {env['torch']}, Python {env['python']}, "
        f"{env['threads']} threads.\n")
    lines.append(
        f"**Model:** {m['params_m']}M params · {m['n_layer']}L/{m['n_head']}H/"
        f"{m['n_embd']}d · block {m['block_size']} · vocab {m['vocab_size']}. "
        f"**Workload:** prompt {c['prompt_len']} → {c['new_tokens']} new tokens, "
        f"{c['repeats']} repeats.\n")

    lines.append("\n## 1. KV-cache (greedy decode, identical outputs)\n")
    lines.append("| variant | tokens/sec | p50 latency (ms) | p95 latency (ms) | TTFT p50 (ms) | peak mem (MB) |")
    lines.append("| --- | --- | --- | --- | --- | --- |")
    for key, label in (("cache_off", "no cache (O(T²))"), ("cache_on", "KV-cache (O(T))")):
        d = kv[key]
        lines.append(
            f"| {label} | {d['tokens_per_s_mean']} | {d['latency']['p50_ms']} | "
            f"{d['latency']['p95_ms']} | {d['ttft_ms_p50']} | {d['peak_mem_mb']} |")
    lines.append(f"\n**KV-cache speedup: {kv['speedup_x']}× tokens/sec.**\n")

    lines.append("\n## 2. Batching throughput (KV-cache on)\n")
    lines.append("| batch size | tokens/sec | speedup vs b=1 | elapsed (s) |")
    lines.append("| --- | --- | --- | --- |")
    for row in r["batching"]["rows"]:
        lines.append(
            f"| {row['batch_size']} | {row['tokens_per_s']} | "
            f"{row['speedup_vs_b1']}× | {row['elapsed_s']} |")

    q = r["quantization"]
    lines.append("\n## 3. int8 dynamic quantization\n")
    lines.append("| metric | fp32 | int8 | delta |")
    lines.append("| --- | --- | --- | --- |")
    lines.append(f"| model size (MB) | {q['fp32_size_mb']} | {q['int8_size_mb']} | "
                 f"{q['size_reduction_x']}× smaller |")
    lines.append(f"| p50 latency (ms) | {q['fp32_latency_ms_p50']} | {q['int8_latency_ms_p50']} | — |")
    lines.append(f"\nNumerical drift (logit MSE fp32→int8): **{q['logit_mse']}**.\n")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--device", default="cpu")
    ap.add_argument("--quick", action="store_true", help="tiny model / fewer tokens")
    args = ap.parse_args(argv)

    cfg = GPTConfig.tiny() if args.quick else GPTConfig.small()
    bcfg = BenchConfig(new_tokens=32, repeats=2, batch_sizes=(1, 2, 4)) if args.quick \
        else BenchConfig()

    report = run_suite(device=args.device, cfg=cfg, bcfg=bcfg)

    (ROOT / "benchmarks" / "results").mkdir(parents=True, exist_ok=True)
    (ROOT / "benchmarks" / "results" / "latest.json").write_text(json.dumps(report, indent=2))
    md = render_markdown(report)
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "results.md").write_text(md)
    print(md)
    print("wrote benchmarks/results/latest.json and docs/results.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
